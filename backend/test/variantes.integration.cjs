/* Runs against a temporary PostgreSQL schema, never against application tables. */
require('dotenv/config');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { Pool } = require('pg');
const { PrismaClient } = require('@prisma/client');
const { PrismaPg } = require('@prisma/adapter-pg');
const { ComponenteBaseService } = require('../dist/src/componente-base/componente-base.service');
const { CatalogoService } = require('../dist/src/catalogo/catalogo.service');
const { PedidoService } = require('../dist/src/pedido/pedido.service');
const schema = `test_variantes_${Date.now()}`;
const connectionString = process.env.DATABASE_URL || 'postgresql://velas_user:velas_password@localhost:5433/velas_db';
const admin = new Pool({ connectionString });
let prisma;
let pool;
async function run() {
  await admin.query(`CREATE SCHEMA "${schema}"`);
  pool = new Pool({ connectionString, options: `-c search_path=${schema}` });
  const migrations = path.join(__dirname, '../prisma/migrations');
  const names = fs.readdirSync(migrations).filter(n => fs.existsSync(path.join(migrations, n, 'migration.sql'))).sort();
  for (const name of names.filter(n => !n.includes('variantes_esencia'))) await pool.query(fs.readFileSync(path.join(migrations, name, 'migration.sql'), 'utf8'));
  await pool.query(`INSERT INTO "MateriaPrima" (nombre,tipo,"unidadMedida","costoUnitario","stockActual","updatedAt") VALUES ('Vainilla','ESENCIA','GR',2,1000,NOW()),('Lavanda','ESENCIA','GR',5,1000,NOW()),('Cera','CERA','GR',1,10000,NOW());
    INSERT INTO "ComponenteBase" (nombre,"costoProduccion","stockDisponible","updatedAt") VALUES ('Oso',120,10,NOW());
    INSERT INTO "RecetaComponente" ("componenteBaseId","materiaPrimaId","cantidadNecesaria","updatedAt") VALUES (1,1,10,NOW()),(1,3,100,NOW());
    INSERT INTO "CatalogoProducto" (nombre,"precioVenta","requiereEnsamble","updatedAt") VALUES ('Vela Oso',200,true,NOW());
    INSERT INTO "EstructuraEnsamble" ("catalogoProductoId","componenteBaseId","cantidadNecesaria","updatedAt") VALUES (1,1,1,NOW());
    INSERT INTO "Pedido" (cliente,canal,estado,total,"costoTotal",rentabilidad,"updatedAt") VALUES ('Histórico','OTRO','ENTREGADO',200,120,80,NOW());
    INSERT INTO "DetallePedido" ("pedidoId","catalogoProductoId",cantidad,"precioUnitario","costoUnitario","updatedAt") VALUES (1,1,1,200,120,NOW());`);
  await pool.query(fs.readFileSync(path.join(migrations, '20260913000000_variantes_esencia/migration.sql'), 'utf8'));
  prisma = new PrismaClient({ adapter: new PrismaPg(pool, { schema }) });
  const comp = new ComponenteBaseService(prisma);
  const cat = new CatalogoService(prisma);
  const sales = new PedidoService(prisma);
  let c = await comp.findOne(1, 'ADMIN');
  assert.equal(c.variantes[0].stockDisponible, 10);
  assert.equal((await cat.findOne(1, 'ADMIN')).variantes[0].precioVenta, 200);
  assert.equal((await sales.findOne(1, 'ADMIN')).detalles[0].descripcionVariante, null);
  console.log('PASS migration preserves stock, prices and old orders');
  await comp.addVariante(1, 2);
  c = await comp.findOne(1, 'ADMIN');
  const vanilla = c.variantes.find(v => v.esenciaId === 1);
  const lavender = c.variantes.find(v => v.esenciaId === 2);
  assert.equal(vanilla.costoProduccion, 120);
  assert.equal(lavender.costoProduccion, 150);
  assert.equal(lavender.stockDisponible, 0);
  await assert.rejects(comp.addVariante(1, 2));
  await assert.rejects(comp.addVariante(1, 3));
  await comp.fabricar(1, lavender.id, 3);
  assert.equal((await prisma.materiaPrima.findUnique({where:{id:2}})).stockActual, 970);
  assert.equal((await prisma.materiaPrima.findUnique({where:{id:1}})).stockActual, 1000);
  assert.equal((await comp.findOne(1,'ADMIN')).stockDisponible, 13);
  await assert.rejects(comp.fabricar(1, lavender.id, 1000));
  assert.equal((await prisma.materiaPrima.findUnique({where:{id:2}})).stockActual, 970);
  console.log('PASS costs differ and production consumes only selected essence, rollback on shortage');
  const cv = await cat.saveVariante(1, { nombre: 'Lavanda', precioVenta: 260, componenteVarianteIds: [lavender.id] });
  const original = (await cat.findOne(1, 'ADMIN')).variantes.find(v => v.nombre === 'Original');
  await assert.rejects(cat.saveVariante(1, {nombre:'Inválida',precioVenta:10,componenteVarianteIds:[]}));
  const order = await sales.create({cliente:'Test',canal:'OTRO',detalles:[{catalogoProductoId:1,varianteId:original.id,cantidad:2},{catalogoProductoId:1,varianteId:cv.id,cantidad:1}]});
  assert.equal(order.total,660); assert.equal(order.costoTotal,390);
  assert.equal(order.detalles.length,2);
  assert.match(order.detalles[1].descripcionVariante,/Oso · Lavanda/);
  c=await comp.findOne(1,'ADMIN');
  assert.equal(c.variantes.find(v=>v.id===vanilla.id).stockDisponible,8);
  assert.equal(c.variantes.find(v=>v.id===lavender.id).stockDisponible,2);
  await assert.rejects(sales.create({cliente:'Bad',canal:'OTRO',detalles:[{catalogoProductoId:1,cantidad:1}]}));
  await assert.rejects(sales.create({cliente:'Bad',canal:'OTRO',detalles:[{catalogoProductoId:1,varianteId:cv.id,cantidad:-1}]}));
  await assert.rejects(sales.create({cliente:'Bad',canal:'OTRO',detalles:[{catalogoProductoId:1,varianteId:original.id,cantidad:1},{catalogoProductoId:1,varianteId:cv.id,cantidad:99}]}));
  assert.equal((await comp.findOne(1,'ADMIN')).variantes.find(v=>v.id===vanilla.id).stockDisponible,8);
  console.log('PASS same candle with two aromas in one sale, price and stock validation, transactional rollback');
  await cat.saveVariante(1,{id:cv.id,nombre:'Nuevo nombre',precioVenta:300,componenteVarianteIds:[lavender.id]});
  await prisma.materiaPrima.update({where:{id:2},data:{costoUnitario:8}});
  const old = await sales.findOne(order.id,'ADMIN');
  assert.equal(old.total,660); assert.equal(old.costoTotal,390); assert.match(old.detalles[1].descripcionVariante,/Lavanda: Oso · Lavanda/);
  assert.equal((await cat.findOne(1,'ADMIN')).variantes.find(v=>v.id===cv.id).costoProduccion,180);
  for(const data of [await comp.findAll('OPERATIVO'),await cat.findAll('OPERATIVO'),await sales.findAll('OPERATIVO')]) {
    assert.doesNotMatch(JSON.stringify(data),/"costoProduccion"|"costoUnitario"|"costoTotal"|"rentabilidad"/);
  }
  console.log('PASS historical snapshots and role restrictions; current costs refresh after material price changes');
  const concurrent = await Promise.allSettled([1,2].map(()=>sales.create({cliente:'Concurrent',canal:'OTRO',detalles:[{catalogoProductoId:1,varianteId:cv.id,cantidad:2}]})));
  assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1);
  assert.equal((await comp.findOne(1,'ADMIN')).variantes.find(v=>v.id===lavender.id).stockDisponible,0);
  console.log('PASS concurrent sales cannot oversell');
}
run().catch(err=>{console.error(err);process.exitCode=1;}).finally(async()=>{
  if(prisma) await prisma.$disconnect();
  if(pool) await pool.end();
  await admin.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
  await admin.end();
});
